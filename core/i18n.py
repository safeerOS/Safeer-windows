_current_lang = "sl"

def detect_system_language():
    """Detects system language or defaults to English."""
    try:
        loc = locale.getdefaultlocale()[0] or os.environ.get("LANG", "")
        code = loc[:2].lower()
        if code in SUPPORTED_LANGUAGES:
            return code
    except Exception:
        pass
    return "en"

def set_language(lang_code: str):
    global _current_lang
    if lang_code == "auto":
        _current_lang = detect_system_language()
    elif lang_code in SUPPORTED_LANGUAGES:
        _current_lang = lang_code
    else:
        _current_lang = "en"

def get_current_language():
    return _current_lang

def t(key: str, default: str = "") -> str:
    """Translates key to current language, falling back to English, then default."""
    lang_dict = TRANSLATIONS.get(_current_lang, TRANSLATIONS["en"])
    if key in lang_dict:
        return lang_dict[key]
    en_dict = TRANSLATIONS["en"]
    if key in en_dict:
        return en_dict[key]
    return default or key
